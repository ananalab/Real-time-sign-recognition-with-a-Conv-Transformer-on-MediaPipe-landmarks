"""Write experiments/lsfb_{scratch,transfer}.yaml: LSFB learning curves (scratch vs. ASL).

The number of epochs grows as the training set shrinks so that every run performs a
comparable number of updates; small runs load data in the main process.

    uv run python scripts/gen_lsfb_experiments.py
"""

from __future__ import annotations

from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
SIZES = {5: 300, 10: 200, 25: 120, 50: 80, 100: 60, "all": 60}  # examples per sign: epochs
SEEDS = (0, 1, 2)
PRETRAINED = "models/asl-transformer-s0/best.pt"
DATA = ["data.root=data/processed/lsfb_isol", "data.split=splits/lsfb_isol_signer.json",
        "train.cache_val=true"]  # fmt: skip


def run(name: str, n: int | str, seed: int, extra: list[str]) -> dict:
    epochs = SIZES[n]
    over = [
        *DATA,
        f"seed={seed}",
        f"train.epochs={epochs}",
        f"train.patience={max(12, epochs // 4)}",
    ]
    if n != "all":
        over += [f"data.max_per_class={n}", "train.num_workers=0"]
    return {"run_name": f"{name}-n{n}-s{seed}", "overrides": over + extra}


def main() -> None:
    runs = []
    for n in SIZES:
        for seed in SEEDS:
            runs.append(run("lsfb-scratch", n, seed, []))
            runs.append(run("lsfb-ft", n, seed, [f"transfer.init_from={PRETRAINED}"]))
    for seed in SEEDS:
        freeze = [f"transfer.init_from={PRETRAINED}", "transfer.freeze_epochs=5"]
        runs.append(run("lsfb-ftfreeze", "all", seed, freeze))
    for r in runs:
        if r["run_name"].endswith("-nall-s0") and "freeze" not in r["run_name"]:
            r["evaluate"] = ["val", "test"]
    scratch = [r for r in runs if r["run_name"].startswith("lsfb-scratch")]
    transfer = [r for r in runs if not r["run_name"].startswith("lsfb-scratch")]
    specs = {
        "lsfb_scratch.yaml": {"name": "lsfb-scratch", "sources": ["lsfb_isol"], "runs": scratch},
        "lsfb_transfer.yaml": {
            "name": "lsfb-transfer",
            "sources": ["lsfb_isol"],
            "pretrained_from": ["anaisazouaoui/signrec-asl-main"],
            "runs": transfer,
        },
    }
    for fname, spec in specs.items():
        out = ROOT / "experiments" / fname
        header = "# generated by scripts/gen_lsfb_experiments.py\n"
        out.write_text(header + yaml.safe_dump(spec, sort_keys=False))
        print(f"{len(spec['runs'])} runs -> {out.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
